const residencyNames = new Set(sourceResidencyObjects);

type SourceIdentity = Pick<SceneManifest, 'id' | 'sourceRevision' | 'sourceSha256'>;

/** True for authored visibility; false only for the reviewed residency windows. */
export function shouldUseSourceVisibility(manifest: SourceIdentity, objectName: string): boolean {
  return manifest.id !== residencySource.id
    || manifest.sourceRevision !== residencySource.revision
    || manifest.sourceSha256 !== residencySource.sha256
    || !residencyNames.has(objectName);
}
