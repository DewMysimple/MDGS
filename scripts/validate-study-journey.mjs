import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { preview } from 'vite';

const { chromium } = createRequire(import.meta.url)(process.env.MDGS_PLAYWRIGHT_MODULE || 'playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'reports/study');
await mkdir(output, { recursive: true });
const server = await preview({ preview: { host: '127.0.0.1', port: 0 }, logLevel: 'error' });
const url = server.resolvedUrls.local[0];
const browser = await chromium.launch({ headless: true, executablePath: process.env.MDGS_TEST_BROWSER });
const failures = [], errors = [], results = [];
const phase = page => page.locator('[data-journey-phase]').getAttribute('data-journey-phase');
const waitPhase = (page, value) => page.waitForFunction(value => document.querySelector('[data-journey-phase]')?.dataset.journeyPhase === value, value, { timeout: 60000 });
const shot = (page, name) => page.screenshot({ path: path.join(output, `${name}.png`), fullPage: true });
const installObserver = async page => {
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.journeyPhases = [];
    new MutationObserver(() => {
      const current = document.querySelector('[data-journey-phase]')?.dataset.journeyPhase;
      if (current && window.journeyPhases.at(-1)?.phase !== current) window.journeyPhases.push({ phase: current, at: performance.now() });
    }).observe(document, { subtree: true, attributes: true, childList: true, attributeFilter: ['data-journey-phase'] });
  });
};
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await installObserver(page);
  const unexpectedResponses = [];
  page.on('response', response => { if (response.url().startsWith(url) && response.status() >= 400) unexpectedResponses.push(response.url()); });
  let releaseTextures;
  const held = new Promise(resolve => { releaseTextures = resolve; });
  await page.route('**/*.webp', async route => { await held; await route.continue().catch(() => {}); });
  await page.goto(url);
  await page.locator('.study-original').evaluate(image => image.decode());
  assert.equal(await phase(page), 'HOME');
  assert.equal(await page.locator('.study-scroll-hotspot').count(), 4);
  assert.equal(await page.locator('canvas').count(), 0, 'Home does not retain a WebGL renderer.');
  await shot(page, 'home-desktop');
  await page.locator('[data-chapter-id="1"]').hover();
  await page.locator('.study-hover-label').waitFor();
  await shot(page, 'home-hover');
  const started = Date.now();
  await page.locator('[data-chapter-id="1"]').click();
  assert.equal(new URL(page.url()).hash, '#chapter-1');
  await page.locator('[data-chapter-id="2"]').dispatchEvent('click');
  assert.equal(new URL(page.url()).hash, '#chapter-1', 'Repeated/other selection is locked.');
  await waitPhase(page, 'SCROLL_LOADING');
  await page.waitForTimeout(950);
  assert.equal(await phase(page), 'SCROLL_LOADING', 'Held real textures must keep the art scene open.');
  assert.equal(await page.locator('.scene-viewport').getAttribute('aria-disabled'), 'true');
  assert.notEqual(await page.locator('.art-loading').getAttribute('data-preparation-stage'), 'ready');
  await shot(page, 'loading-desktop');
  releaseTextures();
  await waitPhase(page, 'SCROLL_VIEWER');
  const enteredMs = Date.now() - started;
  assert(enteredMs >= 3500, 'The complete ceremony must never be an instant navigation.');
  assert.equal(await page.locator('canvas').getAttribute('data-chapter'), '1');
  assert.equal(Number(await page.locator('canvas').getAttribute('data-texture-failed')), 0);
  await page.locator('.skip-link').evaluate(link => link.click());
  assert.equal(await phase(page), 'SCROLL_VIEWER', 'In-page skip link must not change chapter routing.');
  await shot(page, 'viewer-desktop');
  const seen = await page.evaluate(() => window.journeyPhases);
  for (const expected of ['HOME','SCROLL_AWAKENING','CAMERA_ENTERING','ARTISTIC_TRANSITION','SCROLL_LOADING','PAINTING_REVEAL','ENTERING_VIEWER','SCROLL_VIEWER']) assert(seen.some(item => item.phase === expected), expected);
  results.push({ test: 'full-ceremony-real-textures-lock-and-first-frame', enteredMs, phases: seen, passed: true });
  await page.getByRole('button', { name: '下一分镜', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('canvas')?.dataset.progress) > .02);
  await page.waitForTimeout(1200);
  const saved = Number(await page.locator('canvas').getAttribute('data-progress'));
  await page.reload();
  await waitPhase(page, 'SCROLL_VIEWER');
  const restored = Number(await page.locator('canvas').getAttribute('data-progress'));
  assert(Math.abs(saved - restored) < .02, 'Refresh restores the same chapter and session position.');
  results.push({ test: 'refresh-position-restoration', saved, restored, passed: true });
  await page.getByRole('button', { name: '返回书房', exact: true }).click();
  await waitPhase(page, 'RETURNING_HOME');
  await shot(page, 'returning-home');
  await waitPhase(page, 'HOME');
  assert.equal(await page.locator('canvas').count(), 0);
  for (const id of [2,3,4]) {
    // Actual image-space hit position; SVG and image share the exact same transform.
    const box = await page.locator('.study-original').boundingBox();
    const x = [316,655,1035,1370][id - 1];
    const entryStarted = Date.now();
    await page.mouse.click(box.x + box.width * x / 1672, box.y + box.height * 575 / 941);
    await waitPhase(page, 'SCROLL_LOADING');
    assert((await page.locator('.art-loading__colour').getAttribute('src')).endsWith(`painting-${id}.png`));
    await page.waitForTimeout(450);
    await shot(page, `loading-chapter-${id}`);
    await waitPhase(page, 'SCROLL_VIEWER');
    const entryMs = Date.now() - entryStarted;
    assert.equal(Number(await page.locator('canvas').getAttribute('data-chapter')), id);
    assert.equal(await page.locator('canvas').count(), 1);
    await page.getByRole('button', { name: '返回书房', exact: true }).click();
    await waitPhase(page, 'HOME');
    results.push({ test: `original-polygon-to-chapter-${id}`, entryMs, passed: true });
  }
  await page.goBack();
  await waitPhase(page, 'SCROLL_VIEWER');
  assert.equal(Number(await page.locator('canvas').getAttribute('data-chapter')), 4);
  await page.goForward();
  await waitPhase(page, 'HOME');
  // Back out during an active preload, then forward again: old asynchronous work stays invalid.
  await page.locator('[data-chapter-id="2"]').click();
  await page.goBack();
  await waitPhase(page, 'HOME');
  await page.waitForTimeout(1600);
  assert.equal(await phase(page), 'HOME');
  await page.goForward();
  await waitPhase(page, 'SCROLL_VIEWER');
  assert.equal(Number(await page.locator('canvas').getAttribute('data-chapter')), 2);
  results.push({ test: 'history-back-forward-and-cancel-pending-journey', passed: true });
  await page.getByRole('button', { name: '返回书房', exact: true }).click();
  await waitPhase(page, 'HOME');
  const cachedStart = Date.now();
  await page.locator('[data-chapter-id="1"]').click();
  await waitPhase(page, 'SCROLL_VIEWER');
  results.push({ test: 'cached-complete-ceremony', elapsedMs: Date.now() - cachedStart, passed: true });
  assert.deepEqual(unexpectedResponses, []);

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await installObserver(mobile);
  await mobile.goto(url);
  assert.equal(await mobile.locator('.study-mobile-directory > button').count(), 4);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await shot(mobile, 'home-mobile');
  await mobile.getByRole('button', { name: '书房环境动画', exact: true }).tap();
  assert.equal(await mobile.locator('.study-motion-toggle').getAttribute('aria-pressed'), 'false');
  await mobile.getByRole('button', { name: '展卷：锦绣花意', exact: true }).tap();
  await waitPhase(mobile, 'SCROLL_LOADING');
  await shot(mobile, 'loading-mobile');
  await waitPhase(mobile, 'SCROLL_VIEWER');
  assert.equal(Number(await mobile.locator('canvas').getAttribute('data-chapter')), 3);
  await shot(mobile, 'viewer-mobile');
  await mobile.getByRole('button', { name: '打开文化解读' }).tap();
  await mobile.getByRole('dialog').waitFor();
  await mobile.getByRole('button', { name: '关闭文化解读' }).tap();
  await mobile.getByRole('button', { name: '返回书房', exact: true }).tap();
  await waitPhase(mobile, 'HOME');
  assert.equal(await mobile.locator('.study-motion-toggle').getAttribute('aria-pressed'), 'false');
  results.push({ test: 'mobile-touch-directory-viewer-culture-return-and-motion-preference', passed: true });

  const recovery = await browser.newPage({ viewport: { width: 1280, height: 720 }, reducedMotion: 'reduce' });
  await installObserver(recovery);
  let failManifest = true;
  await recovery.route('**/chapter-4/scene.json', route => failManifest ? route.fulfill({ status: 503, body: 'temporarily unavailable' }) : route.continue());
  await recovery.goto(`${url}#chapter-4`);
  await recovery.locator('.art-loading__retry').waitFor();
  await shot(recovery, 'loading-error');
  assert.notEqual(await phase(recovery), 'SCROLL_VIEWER');
  failManifest = false;
  await recovery.getByRole('button', { name: '重新展卷', exact: true }).click();
  await waitPhase(recovery, 'SCROLL_VIEWER');
  assert.equal(await recovery.locator('canvas').getAttribute('data-chapter'), '4');
  results.push({ test: 'deep-link-manifest-error-retry-and-reduced-motion', passed: true });
  const artwork = await browser.newPage({ viewport: { width: 1280, height: 720 }, reducedMotion: 'reduce' });
  await installObserver(artwork);
  let failArt = true;
  await artwork.route('**/painting-2.png', route => failArt ? route.fulfill({ status: 503, body: 'artwork unavailable' }) : route.continue());
  await artwork.goto(`${url}#chapter-2`);
  await artwork.locator('.art-loading__retry').waitFor();
  assert.notEqual(await phase(artwork), 'SCROLL_VIEWER', 'A missing ceremonial painting must not reveal an incomplete art scene.');
  failArt = false;
  await artwork.getByRole('button', { name: '重新展卷', exact: true }).click();
  await waitPhase(artwork, 'SCROLL_VIEWER');
  results.push({ test: 'chapter-painting-decode-failure-gate-and-retry', passed: true });
  assert.deepEqual(errors, []);
} catch (error) { failures.push(error.stack || String(error)); }
finally {
  await browser.close();
  await new Promise(resolve => server.httpServer.close(resolve));
}
const report = { status: failures.length ? 'fail' : 'pass', testedAt: new Date().toISOString(), scope: 'Windows Edge desktop browser and emulated mobile touch; production Vite build. No physical mobile device or cross-browser claim.', results, errors, failures };
await writeFile(path.join(output, 'validation-journey.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
assert.deepEqual(failures, []);
